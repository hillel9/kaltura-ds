#!/usr/bin/env python3
"""
Maintainer helper (NOT needed to use the DS): regenerates ds-icons.js from Icons/16 and Icons/24.

    python3 tools/bundle-icons.py

- width/height are stripped from the root <svg> (the <ds-icon> element sets them)
- fill/stroke="black" becomes currentColor so icons follow the text color
- white knockout <circle> becomes transparent (else the glyph vanishes in dark theme); #D9D9D9 accent and clipPath rects are kept
- output is a classic script: works over file://, no fetch
"""
import os, re, json

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..'))
OUT = os.path.join(ROOT, 'ds-icons.js')


def convert(svg):
    svg = svg.strip()
    svg = re.sub(r'\s*\n\s*', '', svg)                     # single line
    svg = re.sub(r'(fill|stroke)="black"', r'\1="currentColor"', svg)
    # white knockout circles (resolved, remove-alt) must not be white: they hide the glyph in dark theme
    svg = re.sub(r'(<circle\b[^>]*?)fill="white"', r'\1fill="transparent"', svg)

    def fix_root(m):
        tag = m.group(0)
        tag = re.sub(r'\s(width|height)="[^"]*"', '', tag)
        return tag
    svg = re.sub(r'<svg\b[^>]*>', fix_root, svg, count=1)
    return svg


def main():
    icons = {}
    for size in ('16', '24'):
        d = os.path.join(ROOT, 'Icons', size)
        icons[size] = {}
        for f in sorted(os.listdir(d)):
            if not f.endswith('.svg'):
                continue
            name = f[:-4]
            assert re.fullmatch(r'[a-z0-9]+(-[a-z0-9]+)*', name), f'not kebab-case: {size}/{f}'
            with open(os.path.join(d, f), encoding='utf-8') as fh:
                icons[size][name] = convert(fh.read())

    lines = [
        '/* ds-icons.js - generated by tools/bundle-icons.py. Do not edit by hand. */',
        '(function () {',
        '  var icons = window.DS_ICONS = window.DS_ICONS || {};',
    ]
    for size in ('16', '24'):
        lines.append(f'  icons[{size}] = Object.assign(icons[{size}] || {{}}, {{')
        items = sorted(icons[size].items())
        for i, (name, svg) in enumerate(items):
            comma = ',' if i < len(items) - 1 else ''
            lines.append(f'    {json.dumps(name)}: {json.dumps(svg)}{comma}')
        lines.append('  });')
    lines += [
        "  document.dispatchEvent(new CustomEvent('ds-icons-ready'));",
        '})();',
        '',
    ]
    with open(OUT, 'w', encoding='utf-8') as fh:
        fh.write('\n'.join(lines))
    print(f"wrote {OUT}: {len(icons['16'])} x 16px, {len(icons['24'])} x 24px")


if __name__ == '__main__':
    main()
